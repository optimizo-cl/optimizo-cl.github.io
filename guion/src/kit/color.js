/* Color: leer tokens y medir contraste WCAG en vivo (los números del guion se calculan, no se escriben a mano). */
export function colorDe(variable) {
  return getComputedStyle(document.documentElement).getPropertyValue(variable).trim().toUpperCase();
}

function luminancia(hex) {
  const h = hex.replace("#", "");
  const c = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

export function contraste(a, b) {
  const [x, y] = [luminancia(a), luminancia(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}
